"""Proxy-only selective metadata acquisition. Images/model archives are forbidden."""
import csv
import io
import json
import os
import re
import subprocess
import time
import urllib.request

PROXY = 'http://127.0.0.1:7897'
BASE = 'https://huggingface.co/datasets/xmcmic/PMC-VQA/resolve/main/'
FILES = [('train.csv',38081707),('test.csv',10710861),('test_2.csv',12446345)]
RECEIVER = os.environ['RECEIVER_ENTRY']
OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({'http':PROXY,'https':PROXY}))


def send(name, data, receipt):
    header=json.dumps(dict(name=name,receipt=receipt)).encode()+b'\n'
    p=subprocess.run(['ssh','pro5000','python3 '+RECEIVER],input=header+data,capture_output=True)
    if p.returncode:
        raise RuntimeError(p.stderr.decode()[-2000:])
    print(p.stdout.decode(),flush=True)


def main():
    started=time.time();used=0
    for name,size in FILES:
        assert used+size<=64*1024*1024
        req=urllib.request.Request(BASE+name,headers={'User-Agent':'SourceEvidenceMetadataAudit/2.0'})
        with OPENER.open(req,timeout=60) as response:
            data=response.read(size+1)
            assert len(data)==size,'Metadata size differs from inspected author manifest'
            receipt=dict(source_URL=BASE+name,HTTP=response.status,source_download_bytes=len(data),
                         acquisition_epoch=time.time(),proxy=PROXY,read_student_outputs=False)
        used+=len(data)
        if name.startswith('test'):
            # Exclusion-only metadata: never retain/retrieve test questions or answers.
            records=list(csv.DictReader(io.StringIO(data.decode('utf-8-sig'))))
            images=sorted({r['Figure_path'] for r in records});papers=sorted({re.search(r'PMC\d+',s).group() for s in images})
            projected=json.dumps(dict(use='EXCLUSION_ONLY_NO_QA',images=images,papers=papers)).encode()
            receipt.update(stored_bytes=len(projected),stored_QA=False,question_answer_fields_discarded=True)
            send(name+'.EXCLUSION_IDS.json',projected,receipt)
        else:
            receipt.update(stored_bytes=len(data),split='train',QA_origin='AUTHOR_RELEASED_AUTOGENERATED_QA_RETRIEVAL_ONLY')
            send(name,data,receipt)
    send('ACQUISITION_COMPLETE.json',json.dumps(dict(status='METADATA_ACQUISITION_COMPLETE',download_bytes=used,
                                                   wall_seconds=time.time()-started,image_download_bytes=0,
                                                   large_image_archives_downloaded=False)).encode(),
         dict(source_download_bytes=0,acquisition_epoch=time.time()))


if __name__=='__main__':
    main()
